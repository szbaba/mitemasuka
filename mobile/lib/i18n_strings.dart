String localizeSystemText(String rawText, String lang) {
  if (lang == 'tr') return rawText;
  final joinMatch =
      RegExp(r'^(.+?)\s+odaya katıldı\.?$', caseSensitive: false).firstMatch(rawText);
  if (joinMatch != null) {
    final name = joinMatch.group(1) ?? '';
    switch (lang) {
      case 'en':
        return '$name joined the room.';
      case 'ja':
        return '$name が入室しました。';
      case 'de':
        return '$name ist dem Raum beigetreten.';
      case 'es':
        return '$name se unió a la sala.';
      case 'fr':
        return '$name a rejoint le salon.';
      case 'ru':
        return '$name вошел(а) в комнату.';
      case 'ar':
        return 'انضم $name إلى الغرفة.';
    }
  }
  final leaveMatch =
      RegExp(r'^(.+?)\s+odadan ayrıldı\.?$', caseSensitive: false).firstMatch(rawText);
  if (leaveMatch != null) {
    final name = leaveMatch.group(1) ?? '';
    switch (lang) {
      case 'en':
        return '$name left the room.';
      case 'ja':
        return '$name が退室しました。';
      case 'de':
        return '$name hat den Raum verlassen.';
      case 'es':
        return '$name salió de la sala.';
      case 'fr':
        return '$name a quitté le salon.';
      case 'ru':
        return '$name покинул(а) комнату.';
      case 'ar':
        return 'غادر $name الغرفة.';
    }
  }
  return rawText;
}
