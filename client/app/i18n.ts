export type LangCode = 'tr' | 'en' | 'ja' | 'de' | 'es' | 'fr' | 'ru' | 'ar';

export interface LangOption {
  code: LangCode;
  label: string;
  short: string;
  speechLang: string;
}

export const SUPPORTED_LANGS: LangOption[] = [
  { code: 'tr', label: 'Türkçe', short: 'TR', speechLang: 'tr-TR' },
  { code: 'en', label: 'English', short: 'EN', speechLang: 'en-US' },
  { code: 'ja', label: '日本語', short: 'JA', speechLang: 'ja-JP' },
  { code: 'de', label: 'Deutsch', short: 'DE', speechLang: 'de-DE' },
  { code: 'es', label: 'Español', short: 'ES', speechLang: 'es-ES' },
  { code: 'fr', label: 'Français', short: 'FR', speechLang: 'fr-FR' },
  { code: 'ru', label: 'Русский', short: 'RU', speechLang: 'ru-RU' },
  { code: 'ar', label: 'العربية', short: 'AR', speechLang: 'ar-SA' },
];

export function detectBrowserLang(): LangCode {
  if (typeof window === 'undefined') return 'tr';
  try {
    const saved = localStorage.getItem('mitemasuka_lang') as LangCode | null;
    if (saved && SUPPORTED_LANGS.some((l) => l.code === saved)) {
      return saved;
    }
    const nav = (navigator.language || 'en').toLowerCase();
    for (const l of SUPPORTED_LANGS) {
      if (nav.startsWith(l.code)) return l.code;
    }
  } catch {}
  return 'en';
}

export async function translateTextFree(
  text: string,
  targetLang: LangCode
): Promise<{ translated: string; detectedLang?: string } | null> {
  const clean = text.trim();
  if (!clean || clean.length < 2) return null;
  // Sadece sayı, emoji veya noktalama ise çevirme
  if (!new RegExp('\\p{L}', 'u').test(clean)) return null;

  try {
    const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=${encodeURIComponent(
      targetLang
    )}&dt=t&q=${encodeURIComponent(clean)}`;
    const res = await fetch(url);
    if (!res.ok) return null;
    const data = await res.json();
    if (!Array.isArray(data) || !Array.isArray(data[0])) return null;
    const translated = data[0]
      .map((part: unknown[]) => (Array.isArray(part) ? String(part[0] || '') : ''))
      .join('')
      .trim();
    const detectedLang = typeof data[2] === 'string' ? data[2].toLowerCase() : undefined;
    if (!translated || translated.toLowerCase() === clean.toLowerCase()) {
      return null;
    }
    if (detectedLang && detectedLang.startsWith(targetLang)) {
      return null;
    }
    return { translated, detectedLang };
  } catch {
    return null;
  }
}

export function localizeSystemMessage(rawText: string, lang: LangCode): string {
  if (lang === 'tr') return rawText;

  // "User_123 odaya katıldı." / "User_123 odadan ayrıldı." / "User_123 artık NewName olarak biliniyor."
  const joinMatch = rawText.match(/^(.+?)\s+odaya katıldı\.?$/i);
  if (joinMatch) {
    const name = joinMatch[1];
    const map: Record<LangCode, string> = {
      tr: `${name} odaya katıldı.`,
      en: `${name} joined the room.`,
      ja: `${name} が入室しました。`,
      de: `${name} ist dem Raum beigetreten.`,
      es: `${name} se unió a la sala.`,
      fr: `${name} a rejoint le salon.`,
      ru: `${name} вошел(а) в комнату.`,
      ar: `انضم ${name} إلى الغرفة.`,
    };
    return map[lang] || map.en;
  }

  const leaveMatch = rawText.match(/^(.+?)\s+odadan ayrıldı\.?$/i);
  if (leaveMatch) {
    const name = leaveMatch[1];
    const map: Record<LangCode, string> = {
      tr: `${name} odadan ayrıldı.`,
      en: `${name} left the room.`,
      ja: `${name} が退室しました。`,
      de: `${name} hat den Raum verlassen.`,
      es: `${name} salió de la sala.`,
      fr: `${name} a quitté le salon.`,
      ru: `${name} покинул(а) комнату.`,
      ar: `غادر ${name} الغرفة.`,
    };
    return map[lang] || map.en;
  }

  return rawText;
}

